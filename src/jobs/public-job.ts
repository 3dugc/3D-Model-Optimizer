import type { CloudJob } from './types';

export type PublicCloudJob = Omit<CloudJob, 'callbackSigningSecret'>;

export function toPublicCloudJob(job: CloudJob): PublicCloudJob {
  return {
    id: job.id,
    tenantId: job.tenantId,
    externalJobId: job.externalJobId,
    idempotencyKey: job.idempotencyKey,
    taskType: job.taskType,
    task: job.task,
    status: job.status,
    preset: job.preset,
    options: job.options,
    inputBucket: job.inputBucket,
    inputRegion: job.inputRegion,
    inputKey: job.inputKey,
    inputEtag: job.inputEtag,
    outputBucket: job.outputBucket,
    outputRegion: job.outputRegion,
    outputKey: job.outputKey,
    reportKey: job.reportKey,
    callbackUrl: job.callbackUrl,
    callbackSecretId: job.callbackSecretId,
    userId: job.userId,
    paymentRequired: job.paymentRequired,
    orderId: job.orderId,
    chargeId: job.chargeId,
    originalFilename: job.originalFilename,
    inputHash: job.inputHash,
    inputHashKind: job.inputHashKind,
    optionsHash: job.optionsHash,
    canonicalOptions: job.canonicalOptions,
    conversion: job.conversion,
    workerId: job.workerId,
    leaseExpiresAt: job.leaseExpiresAt,
    lastHeartbeatAt: job.lastHeartbeatAt,
    attempts: job.attempts,
    maxAttempts: job.maxAttempts,
    errorCode: job.errorCode,
    errorMessage: job.errorMessage,
    createdAt: job.createdAt,
    uploadedAt: job.uploadedAt,
    queuedAt: job.queuedAt,
    startedAt: job.startedAt,
    completedAt: job.completedAt,
  };
}
